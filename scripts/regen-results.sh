#!/usr/bin/env bash
# Regenerate every number the paper cites. CI runs this and fails on a diff,
# so a stale figure cannot outlive a code change.
#
# Two kinds of output. The gated files are byte-identical on every host,
# because they come from decoders that ship in this crate. The host file is a
# cross-language measurement, which is a property of an environment: it
# carries that environment inline and is regenerated but not diff-gated.
# What is checked across environments is the claim, in tests/acceptance.rs.
set -euo pipefail
cd "$(dirname "$0")/.."
cargo build --release --quiet
BIN=./target/release/transit
mkdir -p results

# --- gated: identical on every host -----------------------------------------
"$BIN" differential --in-crate-only --format json > results/differential-incrate.json

# `classify --format json` already emits an array per spec, so concatenating
# them inside another array would give an array of arrays. Key each by its
# file name instead, which is what the paper's table generator reads.
{
  echo '{'
  first=1
  for f in examples/*.openapi.json; do
    [ $first -eq 1 ] || echo ','
    first=0
    printf '  "%s": ' "$(basename "$f" .openapi.json)"
    # `classify` exits 1 on a non-qualifying spec, which is a verdict rather
    # than a failure. Under `set -e` that would abort the whole script on the
    # Slack example, so the exit code is deliberately discarded here.
    "$BIN" classify --spec "$f" --format json || true
  done
  echo '}'
} > results/classify.json

# Same reason: `fuzz` exits 1 when it finds something, which is the expected
# outcome against the hostile scenario.
"$BIN" fuzz --scenario all-hostile --format json > results/fuzz-hostile.json || true
"$BIN" fuzz --scenario boundable --format json > results/fuzz-boundable.json || true
"$BIN" survey survey/desk-study.toml --format json > results/survey-hypothesis.json

# --- ungated: a measurement of this host ------------------------------------
{
  echo '{'
  echo '  "environment": {'
  echo "    \"generated_on\": \"$(uname -sm)\","
  echo "    \"node\": \"$(node --version 2>/dev/null || echo absent)\","
  echo "    \"go\": \"$(go version 2>/dev/null || echo absent)\","
  echo "    \"python\": \"$( (python3 --version || python --version) 2>&1 || echo absent)\","
  echo "    \"ruby\": \"$(ruby --version 2>/dev/null || echo absent)\""
  echo '  },'
  echo '  "run":'
  "$BIN" differential --format json
  echo '}'
} > results/differential-host.json

# --- LaTeX the paper reads directly -----------------------------------------
"$BIN" survey survey/desk-study.toml --format tex > results/survey-hypothesis.tex
{
  echo '% Generated by scripts/regen-results.sh. Do not edit.'
  echo '\begin{tabular}{llr}'
  echo '\toprule'
  echo 'Specification & Verdict & Failing conditions \\'
  echo '\midrule'
  for f in examples/*.openapi.json; do
    name=$(basename "$f" .openapi.json)
    line=$("$BIN" classify --spec "$f" | grep -E '^(GET|POST|PUT|PATCH|DELETE) ' | head -1 || true)
    verdict=$(echo "$line" | sed 's/.*— //')
    # The conditions that FAILED, not every condition mentioned. Read off
    # the text output's `Failed { ... }` lines: grepping the JSON for
    # `"C1"` matches the `conditions` list too, which listed all four
    # against every spec including the Qualified ones — a generated table
    # asserting the opposite of the run that produced it.
    failing=$("$BIN" classify --spec "$f" \
      | grep 'Failed {' | grep -oE 'C[1-4]' | sort -u | paste -sd, - | sed 's/,/, /g' || true)
    echo "\\texttt{${name//_/\\_}} & ${verdict} & ${failing:-none} \\\\"
  done
  echo '\bottomrule'
  echo '\end{tabular}'
} > results/classify-table.tex

echo "wrote results/"
